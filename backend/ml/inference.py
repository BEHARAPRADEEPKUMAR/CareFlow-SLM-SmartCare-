import json
import re
from pathlib import Path

import torch
from transformers import AutoTokenizer, AutoModelForCausalLM
from peft import PeftModel


# ============================================================
# CareFlow-SLM Inference
# Base Model + LoRA Adapter
# ============================================================

BASE_MODEL = "HuggingFaceTB/SmolLM2-360M-Instruct"

BASE_DIR = Path(__file__).resolve().parent
LORA_ADAPTER = BASE_DIR / "careflow-slm-lora"


# ============================================================
# Load Model
# ============================================================

print("=" * 60)
print("Loading CareFlow-SLM")
print("=" * 60)

print("Base model:")
print(BASE_MODEL)

print("LoRA adapter:")
print(LORA_ADAPTER)


# CPU-safe configuration
DEVICE = "cuda" if torch.cuda.is_available() else "cpu"

print("Device:", DEVICE)


# ------------------------------------------------------------
# Tokenizer
# ------------------------------------------------------------

tokenizer = AutoTokenizer.from_pretrained(
    BASE_MODEL
)

if tokenizer.pad_token is None:
    tokenizer.pad_token = tokenizer.eos_token


# ------------------------------------------------------------
# Base model
# ------------------------------------------------------------

base_model = AutoModelForCausalLM.from_pretrained(
    BASE_MODEL,
    torch_dtype=torch.float32,
)

base_model.to(DEVICE)


# ------------------------------------------------------------
# Load LoRA adapter
# ------------------------------------------------------------

model = PeftModel.from_pretrained(
    base_model,
    str(LORA_ADAPTER),
)

model.to(DEVICE)

model.eval()


print("CareFlow-SLM loaded successfully.")
print("=" * 60)


# ============================================================
# Prompt
# ============================================================

SYSTEM_PROMPT = """
You are CareFlow-SLM, a healthcare appointment and
patient communication assistant.

Your job is to understand the user's request and classify
the intent.

Return ONLY valid JSON.

Allowed intents:

BOOK_APPOINTMENT
RESCHEDULE_APPOINTMENT
CANCEL_APPOINTMENT
CHECK_APPOINTMENT
DOCTOR_AVAILABILITY
HOSPITAL_FAQ
APPOINTMENT_REMINDER
GENERAL_QUERY
MEDICAL_QUERY
EMERGENCY
HUMAN_HANDOFF

Extract these fields:

intent
department
doctor_name
date
time

Use null when information is not available.

Do not provide medical diagnosis.
Do not provide prescriptions.
Do not invent doctor information.

Example:

User:
I want to book a cardiologist tomorrow at 3 PM.

Output:
{
  "intent": "BOOK_APPOINTMENT",
  "department": "Cardiology",
  "doctor_name": null,
  "date": "tomorrow",
  "time": "15:00"
}
"""


# ============================================================
# JSON extraction helper
# ============================================================

def extract_json(text):
    """
    Extract the first JSON object generated by the model.
    """

    text = text.strip()

    # Direct JSON
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        pass

    # Search for JSON inside generated text
    match = re.search(
        r"\{.*?\}",
        text,
        re.DOTALL,
    )

    if match:
        try:
            return json.loads(match.group(0))
        except json.JSONDecodeError:
            pass

    return None


# ============================================================
# Clean / validate result
# ============================================================

ALLOWED_INTENTS = {
    "BOOK_APPOINTMENT",
    "RESCHEDULE_APPOINTMENT",
    "CANCEL_APPOINTMENT",
    "CHECK_APPOINTMENT",
    "DOCTOR_AVAILABILITY",
    "HOSPITAL_FAQ",
    "APPOINTMENT_REMINDER",
    "GENERAL_QUERY",
    "MEDICAL_QUERY",
    "EMERGENCY",
    "HUMAN_HANDOFF",
}


def clean_result(result):

    if not isinstance(result, dict):
        return {
            "intent": "GENERAL_QUERY",
            "department": None,
            "doctor_name": None,
            "date": None,
            "time": None,
        }

    intent = str(
        result.get("intent", "GENERAL_QUERY")
    ).upper().strip()

    if intent not in ALLOWED_INTENTS:
        intent = "GENERAL_QUERY"

    department = result.get("department")
    doctor_name = result.get("doctor_name")
    date = result.get("date")
    time = result.get("time")

    if isinstance(department, str):
        department = department.strip()

    if isinstance(doctor_name, str):
        doctor_name = doctor_name.strip()

    if isinstance(date, str):
        date = date.strip()

    if isinstance(time, str):
        time = time.strip()

    return {
        "intent": intent,
        "department": department,
        "doctor_name": doctor_name,
        "date": date,
        "time": time,
    }


# ============================================================
# Main prediction function
# ============================================================

def predict_intent(user_message):
    """
    Run CareFlow-SLM inference.

    Example:

        result = predict_intent(
            "I want to book a cardiologist tomorrow at 3 PM"
        )

    Returns:

        {
            "intent": "BOOK_APPOINTMENT",
            "department": "Cardiology",
            "doctor_name": null,
            "date": "tomorrow",
            "time": "15:00"
        }
    """

    user_message = user_message.strip()

    if not user_message:
        return {
            "intent": "GENERAL_QUERY",
            "department": None,
            "doctor_name": None,
            "date": None,
            "time": None,
        }

    # --------------------------------------------------------
    # Build chat messages
    # --------------------------------------------------------

    messages = [
        {
            "role": "system",
            "content": SYSTEM_PROMPT,
        },
        {
            "role": "user",
            "content": user_message,
        },
    ]

    # --------------------------------------------------------
    # Apply model chat template
    # --------------------------------------------------------

    prompt = tokenizer.apply_chat_template(
        messages,
        tokenize=False,
        add_generation_prompt=True,
    )

    # --------------------------------------------------------
    # Tokenize
    # --------------------------------------------------------

    inputs = tokenizer(
        prompt,
        return_tensors="pt",
        truncation=True,
        max_length=512,
    )

    inputs = {
        key: value.to(DEVICE)
        for key, value in inputs.items()
    }

    # --------------------------------------------------------
    # Generate
    # --------------------------------------------------------

    with torch.no_grad():

        output_ids = model.generate(
            **inputs,
            max_new_tokens=150,
            do_sample=False,
            temperature=0.1,
            top_p=0.9,
            pad_token_id=tokenizer.pad_token_id,
            eos_token_id=tokenizer.eos_token_id,
        )

    # --------------------------------------------------------
    # Remove input tokens
    # --------------------------------------------------------

    generated_ids = output_ids[
        0,
        inputs["input_ids"].shape[1]:
    ]

    generated_text = tokenizer.decode(
        generated_ids,
        skip_special_tokens=True,
    ).strip()

    print("\n----------------------------------------")
    print("User:")
    print(user_message)

    print("\nRaw SLM output:")
    print(generated_text)

    # --------------------------------------------------------
    # Extract JSON
    # --------------------------------------------------------

    result = extract_json(
        generated_text
    )

    result = clean_result(
        result
    )

    print("\nStructured result:")
    print(
        json.dumps(
            result,
            indent=2,
        )
    )

    print("----------------------------------------\n")

    return result


